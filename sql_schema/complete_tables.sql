CREATE TABLE public.words (
  id uuid NOT NULL DEFAULT gen_random_uuid(),
  notebook_id uuid NOT NULL,
  word text NOT NULL,
  translation text NOT NULL,
  example_sentence text,
  notes text,
  current_round integer NOT NULL DEFAULT 1,
  is_mastered boolean NOT NULL DEFAULT false,
  review_date date NOT NULL,
  last_reviewed date,
  times_reviewed integer NOT NULL DEFAULT 0,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  updated_at timestamp with time zone NOT NULL DEFAULT now(),
  page_id uuid,
  meaning text,
  position_in_page integer DEFAULT 1,
  status USER-DEFINED DEFAULT 'learning'::word_status,
  source_notebook_id uuid,
  original_page_id uuid,
  difficulty_tag text NOT NULL DEFAULT 'NORMAL'::text CHECK (difficulty_tag = ANY (ARRAY['NORMAL'::text, 'EXTREMELY_HARD'::text, 'MASTER_LEVEL'::text, 'LEGENDARY'::text])),
  cycle_count integer NOT NULL DEFAULT 0,
  word_type text DEFAULT 'unknown'::text CHECK (word_type = ANY (ARRAY['verb'::text, 'noun'::text, 'adjective'::text, 'adverb'::text, 'preposition'::text, 'conjunction'::text, 'interjection'::text, 'pronoun'::text, 'article'::text, 'other'::text, 'unknown'::text])),
  sentence_meaning text,
  sentence_bold text,
  meaning_bold text,
  is_archived boolean DEFAULT false,
  archived_notebook_id uuid,
  archived_at timestamp with time zone,
  archive_cycle_number integer DEFAULT 1,
  CONSTRAINT words_pkey PRIMARY KEY (id),
  CONSTRAINT words_notebook_id_fkey FOREIGN KEY (notebook_id) REFERENCES public.notebooks(id),
  CONSTRAINT words_page_id_fkey FOREIGN KEY (page_id) REFERENCES public.pages(id),
  CONSTRAINT words_source_notebook_id_fkey FOREIGN KEY (source_notebook_id) REFERENCES public.notebooks(id),
  CONSTRAINT words_original_page_id_fkey FOREIGN KEY (original_page_id) REFERENCES public.pages(id)
);